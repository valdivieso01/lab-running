/**
 * Loads gear items from Cloud Firestore `/gear` if available,
 * falling back seamlessly to the comprehensive local catalog.
 */
export async function loadGearCatalogFromCloud(): Promise<GearItem[]> {
  if (!db) return GEAR_CATALOG;
  try {
    const snap = await getDocs(collection(db, 'gear'));
    if (!snap.empty) {
      const cloudItems: GearItem[] = [];
      snap.forEach((d) => {
        cloudItems.push({ id: d.id, ...(d.data() as Omit<GearItem, 'id'>) });
      });
      // Merge cloud items with local catalog (cloud overrides matching id)
      const cloudIds = new Set(cloudItems.map((i) => i.id));
      const remainingLocal = GEAR_CATALOG.filter((i) => !cloudIds.has(i.id));
      return [...cloudItems, ...remainingLocal];
    }
  } catch (err) {
    // Ignore permissions/network errors and fall back to local
  }
  return GEAR_CATALOG;
}
